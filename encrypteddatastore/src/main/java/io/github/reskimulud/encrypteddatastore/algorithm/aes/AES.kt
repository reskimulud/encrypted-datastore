package io.github.reskimulud.encrypteddatastore.algorithm.aes

import io.github.reskimulud.encrypteddatastore.algorithm.Encryptor
import java.security.SecretKey
import javax.crypto.spec.SecretKeySpec

private const val KEY_ALGORITHM = "AES"

/**
 * AES-GCM [Encryptor].
 *
 * [Builder] selects the algorithm from the key length: 16 bytes for
 * AES-128-GCM, 24 bytes for AES-192-GCM, and 32 bytes for AES-256-GCM.
 *
 * [decryptLegacyCbc] reads values written by version 0.0.3 and is not part of
 * the [Encryptor] contract.
 */
public interface AES : Encryptor {

    /**
     * Decrypts a value written by version 0.0.3 (AES-256-CBC, zero padding).
     *
     * @throws IllegalArgumentException if the key is not 32 bytes, no legacy
     * IV was configured, or the ciphertext is not block aligned.
     */
    public fun decryptLegacyCbc(data: ByteArray): ByteArray

    /**
     * Builds an [AES] instance. The key length is validated here so a wrong
     * key fails before any data is read or written.
     */
    public class Builder {
        private var key: SecretKey? = null
        private var keySizeBytes: Int? = null
        private var legacyIv: ByteArray? = null

        /**
         * Sets the key as UTF-8 bytes. The byte length must be 16, 24, or 32.
         */
        public fun setKey(key: String): Builder = setKey(key.toByteArray(Charsets.UTF_8))

        /**
         * Sets a raw key. The length must be 16, 24, or 32 bytes and selects
         * AES-128, AES-192, or AES-256 respectively.
         */
        public fun setKey(key: ByteArray): Builder =
            setKey(SecretKeySpec(key, KEY_ALGORITHM), key.size * 8)

        /**
         * Sets a key from an external provider, for example an Android Keystore
         * key.
         *
         * [keySizeBits] must be 128, 192, or 256. It is explicit because
         * non-exportable keys return null from [SecretKey.getEncoded], so their
         * length cannot be read. When the key is non-exportable, encryption uses
         * the IV generated by the provider.
         */
        public fun setKey(key: SecretKey, keySizeBits: Int): Builder {
            require(key.algorithm == KEY_ALGORITHM) { "Key algorithm must be AES" }
            require(keySizeBits == 128 || keySizeBits == 192 || keySizeBits == 256) {
                "Key size must be 128, 192, or 256 bits (16, 24, or 32 bytes)"
            }
            this.key = key
            this.keySizeBytes = keySizeBits / 8
            return this
        }

        /**
         * Sets the fixed IV used by version 0.0.3 data. Not used for new data.
         */
        public fun setIv(iv: String): Builder {
            val bytes = iv.toByteArray(Charsets.UTF_8)
            require(bytes.size == AesImpl.BLOCK_SIZE) {
                "Legacy IV must be ${AesImpl.BLOCK_SIZE} bytes (128 bits)"
            }
            this.legacyIv = bytes
            return this
        }

        public fun build(): AES {
            val key = requireNotNull(key) { "Key is required" }
            val keySizeBytes = requireNotNull(keySizeBytes) { "Key is required" }
            return AesImpl(secretKey = key, keySizeBytes = keySizeBytes, iv = legacyIv)
        }
    }
}
